<?php

namespace App\Exports;

use DateTimeImmutable;
use Illuminate\Support\Collection;
use Maatwebsite\Excel\Concerns\FromCollection;
use Maatwebsite\Excel\Concerns\WithCustomValueBinder;
use Maatwebsite\Excel\Concerns\WithCustomStartCell;
use Maatwebsite\Excel\Concerns\WithEvents;
use Maatwebsite\Excel\Concerns\WithHeadings;
use Maatwebsite\Excel\Events\AfterSheet;
use PhpOffice\PhpSpreadsheet\Cell\Coordinate;
use PhpOffice\PhpSpreadsheet\Cell\Cell;
use PhpOffice\PhpSpreadsheet\Cell\DataType;
use PhpOffice\PhpSpreadsheet\Cell\DefaultValueBinder;
use PhpOffice\PhpSpreadsheet\Shared\Date as ExcelDate;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Style\NumberFormat;

/** Standard reports only; the official CSWDO form has its own PDF renderer. */
class ArrayExport extends DefaultValueBinder implements FromCollection, WithHeadings, WithCustomStartCell, WithCustomValueBinder, WithEvents
{
    private const DATE_COLUMNS = ['Date', 'Registered On', 'Checked In', 'Checked Out', 'Last Login', 'Created', 'Last Updated', 'Requested', 'Departed', 'Arrived'];
    private const NUMBER_COLUMNS = ['Rank', 'Age', 'Capacity', 'Current Occupancy', 'Occupancy', 'Households', 'Households Checked-in', 'Family Size', 'Members Present', 'Count', 'Currently Present', 'Matching Members', 'Value (PHP)', 'On Hand', 'Reorder Level', 'Expected', 'Received'];

    public function __construct(
        private array $headings,
        private array $rows,
        private array $metadata = [],
    ) {}

    public function startCell(): string
    {
        return 'A8';
    }

    public function collection(): Collection
    {
        return collect(array_map(function ($row) {
            return array_map(function ($heading, $index) use ($row) {
                $value = $row[$index] ?? '';
                if (in_array($heading, self::DATE_COLUMNS, true) && is_string($value)) {
                    foreach (['!M d, Y h:i A', '!M d, Y'] as $format) {
                        $date = DateTimeImmutable::createFromFormat($format, $value);
                        if ($date !== false) return ExcelDate::dateTimeToExcel($date);
                    }
                }
                if (in_array($heading, self::NUMBER_COLUMNS, true) && is_numeric(str_replace(',', '', (string) $value))) {
                    return (float) str_replace(',', '', (string) $value);
                }
                return is_scalar($value) || $value === null ? ($value ?? '') : json_encode($value, JSON_UNESCAPED_UNICODE);
            }, $this->headings, array_keys($this->headings));
        }, $this->rows));
    }

    public function bindValue(Cell $cell, $value): bool
    {
        // User-entered names, remarks, etc. must never execute as spreadsheet formulas.
        if (is_string($value) && preg_match('/^[=+@\-\t\r]/', $value)) {
            $cell->setValueExplicit($value, DataType::TYPE_STRING);
            return true;
        }
        return parent::bindValue($cell, $value);
    }

    public function headings(): array
    {
        return $this->headings;
    }

    public function registerEvents(): array
    {
        return [AfterSheet::class => function (AfterSheet $event) {
            $sheet = $event->sheet->getDelegate();
            $lastCol = Coordinate::stringFromColumnIndex(max(1, count($this->headings)));
            $lastRow = max(8, 8 + count($this->rows));
            $meta = $this->metadata;
            $dataCount = count($this->rows) - (($this->rows && in_array('TOTAL VALUE', (array) end($this->rows), true)) ? 1 : 0);

            $sheet->mergeCells("A1:{$lastCol}1");
            $sheet->setCellValue('A1', 'EVACTECH  |  CITY OF CABUYAO, LAGUNA');
            $sheet->mergeCells("A2:{$lastCol}2");
            $sheet->setCellValue('A2', $meta['title'] ?? 'Operational Report');
            $sheet->mergeCells("A3:{$lastCol}3");
            $sheet->setCellValue('A3', 'Scope: ' . ($meta['scope'] ?? '-') . '   |   ' . ($meta['context'] ?? 'Current snapshot'));
            $sheet->mergeCells("A4:{$lastCol}4");
            $sheet->setCellValue('A4', 'Generated by: ' . ($meta['generated_by'] ?? '-') . '   |   ' . ($meta['generated_at'] ?? '-') . (! empty($meta['reference']) ? '   |   ' . $meta['reference'] : ''));
            $sheet->mergeCells("A5:{$lastCol}5");
            $sheet->setCellValue('A5', 'Filters: ' . (implode(' | ', $meta['filters'] ?? []) ?: 'None') . '   |   ' . max(0, $dataCount) . ' data rows' . (empty($meta['metrics']) ? '' : '   |   ' . implode('   |   ', array_map(fn ($key, $value) => $key . ': ' . $value, array_keys($meta['metrics']), array_values($meta['metrics'])))));
            $sheet->mergeCells("A6:{$lastCol}6");
            $sheet->setCellValue('A6', trim(($meta['note'] ?? '') . (! empty($meta['sensitive']) ? '  INTERNAL USE — PERSONAL DATA' : '')));

            $sheet->getStyle("A1:{$lastCol}1")->applyFromArray([
                'font' => ['bold' => true, 'color' => ['rgb' => 'FFFFFF'], 'size' => 11],
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '0E7490']],
            ]);
            $sheet->getStyle("A2:{$lastCol}2")->getFont()->setBold(true)->setSize(15);
            $sheet->getStyle("A3:{$lastCol}6")->getFont()->getColor()->setRGB('475569');
            $sheet->getStyle("A3:{$lastCol}6")->getAlignment()->setWrapText(true);
            $sheet->getRowDimension(3)->setRowHeight(30);
            $sheet->getRowDimension(5)->setRowHeight(26);
            $sheet->getRowDimension(6)->setRowHeight(35);

            $headerRange = "A8:{$lastCol}8";
            $sheet->getStyle($headerRange)->applyFromArray([
                'font' => ['bold' => true, 'color' => ['rgb' => 'FFFFFF']],
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '17374C']],
                'alignment' => ['wrapText' => true, 'vertical' => Alignment::VERTICAL_CENTER],
            ]);
            $sheet->getRowDimension(8)->setRowHeight(30);
            if ($this->rows) {
                $dataRange = "A9:{$lastCol}{$lastRow}";
                $sheet->getStyle($dataRange)->getBorders()->getBottom()->setBorderStyle(Border::BORDER_HAIR);
                $sheet->getStyle($dataRange)->getBorders()->getBottom()->getColor()->setRGB('E2E8F0');
                $sheet->getStyle($dataRange)->getAlignment()->setVertical(Alignment::VERTICAL_TOP);
                // Show full text in the cells, while keeping printed pages legible.
                $sheet->getStyle($dataRange)->getAlignment()->setWrapText(true);
            }
            foreach ($this->headings as $i => $heading) {
                $col = Coordinate::stringFromColumnIndex($i + 1);
                if (in_array($heading, self::DATE_COLUMNS, true)) {
                    // Preserve times where the actual report dataset includes them.
                    $hasTime = collect($this->rows)->contains(fn ($row) => preg_match('/[0-9]:[0-9]{2} [AP]M$/', (string) ($row[$i] ?? '')) === 1);
                    $sheet->getStyle("{$col}9:{$col}{$lastRow}")->getNumberFormat()->setFormatCode($hasTime ? 'mmm dd, yyyy hh:mm AM/PM' : 'mmm dd, yyyy');
                } elseif ($heading === 'Value (PHP)') {
                    $sheet->getStyle("{$col}9:{$col}{$lastRow}")->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_NUMBER_COMMA_SEPARATED1);
                }
                // Cap widest text columns: auto-size alone makes some reports impractical to print.
                $sheet->getColumnDimension($col)->setAutoSize(false);
                $maxLen = max(14, mb_strlen((string) $heading));
                foreach (array_slice($this->rows, 0, 200) as $row) {
                    $maxLen = max($maxLen, mb_strlen((string) ($row[$i] ?? '')));
                }
                $sheet->getColumnDimension($col)->setWidth(min(48, max(15, $maxLen + 2)));
            }
            $sheet->freezePane('A9');
            $sheet->setAutoFilter("A8:{$lastCol}{$lastRow}");
            $sheet->getPageSetup()->setFitToWidth(1);
            $sheet->getPageSetup()->setFitToHeight(0);
            $sheet->setShowGridlines(false);
        }];
    }
}
